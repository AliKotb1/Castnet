// Builds the browser-specific copies of the extension from ./extension:
//   dist/extensions/chrome/            Chrome, Edge, Brave, Arc, Vivaldi, Opera (MV3 service worker)
//   dist/extensions/firefox/ + Castnet.xpi   Firefox, Zen, LibreWolf, Floorp (MV3 background script)
//   dist/extensions/safari/            resources for the Safari web extension inside Castnet.app
// Firefox and Safari get one classic background script (each module wrapped in its own scope),
// so they don't depend on module support in background pages.
//   node scripts/build-extensions.mjs
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const src = path.join(root, 'extension');
const out = path.join(root, 'dist', 'extensions');
const base = JSON.parse(fs.readFileSync(path.join(src, 'manifest.json'), 'utf8'));

function copyDir(from, to, skip = () => false) {
  fs.mkdirSync(to, { recursive: true });
  for (const e of fs.readdirSync(from, { withFileTypes: true })) {
    if (e.name.startsWith('.') || skip(e.name)) continue;
    const a = path.join(from, e.name), b = path.join(to, e.name);
    e.isDirectory() ? copyDir(a, b) : fs.copyFileSync(a, b);
  }
}

/** Wraps ES modules into one classic script: each module in an IIFE that returns its exports. */
function bundleBackground() {
  const order = ['lib/detect.js', 'lib/manifests.js', 'lib/probe.js', 'background.js'];
  // Firefox and Safari: run everything against `browser.*` (promise-based everywhere).
  const parts = ['// Generated by scripts/build-extensions.mjs from extension/*.js. Do not edit.',
    '(function (chrome) {', '"use strict";'];
  for (const rel of order) {
    let code = fs.readFileSync(path.join(src, rel), 'utf8');
    const imports = [];
    code = code.replace(/^import\s*\{([^}]*)\}\s*from\s*['"]([^'"]+)['"];?\s*$/gm, (_, names, from) => {
      imports.push({ names: names.split(',').map((n) => n.trim()).filter(Boolean), from });
      return '';
    });
    const exported = [];
    code = code.replace(/^export\s+(async\s+function|function\*?|const|let|class)\s+([A-Za-z0-9_$]+)/gm, (_, kind, name) => {
      exported.push(name);
      return `${kind} ${name}`;
    });
    code = code.replace(/^export\s*\{[^}]*\};?\s*$/gm, '');
    const varName = `__mod_${rel.replace(/[^a-z0-9]/gi, '_')}`;
    const pre = imports.map((i) => {
      const from = `__mod_${path.join(path.dirname(rel), i.from).replace(/^\.\//, '').replace(/[^a-z0-9]/gi, '_')}`;
      return `const { ${i.names.join(', ')} } = ${from};`;
    }).join('\n');
    parts.push(`const ${varName} = (() => {\n${pre}\n${code}\nreturn { ${exported.join(', ')} };\n})();`);
  }
  parts.push('})(globalThis.browser ?? globalThis.chrome);');
  return parts.join('\n\n');
}

const STRIP_FOR_BUNDLE = (n) => n === 'background.js' || n === 'lib' || n === 'manifest.json';
const webAccessible = [{ resources: ['content/inject.js'], matches: ['http://*/*', 'https://*/*'] }];

// Chrome family: the source as-is.
fs.rmSync(out, { recursive: true, force: true });
copyDir(src, path.join(out, 'chrome'));

// Firefox family.
const ffDir = path.join(out, 'firefox');
copyDir(src, ffDir, STRIP_FOR_BUNDLE);
fs.writeFileSync(path.join(ffDir, 'background.bundle.js'), bundleBackground());
const ff = {
  manifest_version: 3,
  name: base.name,
  short_name: base.short_name,
  version: base.version,
  description: base.description,
  browser_specific_settings: {
    gecko: { id: 'castnet@castnet.app', strict_min_version: '128.0', data_collection_permissions: { required: ['none'] } },
  },
  icons: base.icons,
  action: base.action,
  background: { scripts: ['background.bundle.js'] },
  permissions: base.permissions.filter((p) => p !== 'scripting'),
  host_permissions: base.host_permissions,
  content_scripts: base.content_scripts,
  web_accessible_resources: webAccessible,
};
fs.writeFileSync(path.join(ffDir, 'manifest.json'), JSON.stringify(ff, null, 2) + '\n');
const xpi = path.join(out, 'Castnet.xpi');
execFileSync('/usr/bin/zip', ['-q', '-r', '-X', xpi, '.'], { cwd: ffDir });

// Safari.
const sfDir = path.join(out, 'safari');
copyDir(src, sfDir, STRIP_FOR_BUNDLE);
fs.writeFileSync(path.join(sfDir, 'background.bundle.js'), bundleBackground());
const sf = {
  manifest_version: 3,
  name: base.short_name,
  version: base.version,
  description: base.description,
  icons: base.icons,
  action: base.action,
  background: { scripts: ['background.bundle.js'], persistent: false },
  permissions: base.permissions.filter((p) => !['downloads', 'notifications', 'scripting'].includes(p)),
  host_permissions: base.host_permissions,
  content_scripts: base.content_scripts,
  web_accessible_resources: webAccessible,
};
fs.writeFileSync(path.join(sfDir, 'manifest.json'), JSON.stringify(sf, null, 2) + '\n');

// Store uploads (see docs/PUBLISHING.md):
//   castnet-chrome-<v>.zip   Chrome Web Store / Edge Add-ons / Opera (no "key": stores assign their own ID)
//   castnet-firefox-<v>.xpi  addons.mozilla.org (listed or self-distributed signing)
//   castnet-extension-source-<v>.zip  source + build script, which Mozilla's reviewers ask for
const store = path.join(root, 'dist', 'store');
fs.rmSync(store, { recursive: true, force: true });
const chromeStore = path.join(store, 'chrome');
copyDir(path.join(out, 'chrome'), chromeStore);
const cm = JSON.parse(fs.readFileSync(path.join(chromeStore, 'manifest.json'), 'utf8'));
delete cm.key;
fs.writeFileSync(path.join(chromeStore, 'manifest.json'), JSON.stringify(cm, null, 2) + '\n');
execFileSync('/usr/bin/zip', ['-q', '-r', '-X', path.join(store, `castnet-chrome-${base.version}.zip`), '.'], { cwd: chromeStore });
fs.rmSync(chromeStore, { recursive: true, force: true });
fs.copyFileSync(xpi, path.join(store, `castnet-firefox-${base.version}.xpi`));
const srcPkg = path.join(store, 'source');
copyDir(path.join(root, 'extension'), path.join(srcPkg, 'extension'));
fs.mkdirSync(path.join(srcPkg, 'scripts'), { recursive: true });
fs.copyFileSync(path.join(root, 'scripts', 'build-extensions.mjs'), path.join(srcPkg, 'scripts', 'build-extensions.mjs'));
fs.writeFileSync(path.join(srcPkg, 'BUILD.txt'), [
  `Castnet browser extension ${base.version}: source and build steps`, '',
  'Needs Node.js 18 or later; no other tools or packages.',
  '  node scripts/build-extensions.mjs',
  'Output: dist/extensions/firefox/ (the add-on) and dist/extensions/Castnet.xpi.',
  'background.bundle.js is generated: extension/lib/*.js and extension/background.js, each wrapped',
  'in a function scope and concatenated (nothing is minified or obfuscated). All other files are copied as-is.', '',
].join('\n'));
execFileSync('/usr/bin/zip', ['-q', '-r', '-X', path.join(store, `castnet-extension-source-${base.version}.zip`), '.'], { cwd: srcPkg });
fs.rmSync(srcPkg, { recursive: true, force: true });

console.log(`extensions built: ${out}\n  chrome/  firefox/ (+ Castnet.xpi)  safari/\nstore packages: ${store}`);
