import Foundation

/// One quality choice offered in the browser menu for a site page (YouTube etc.).
public struct SiteFormatOption: Codable {
    public var id: String
    public var label: String        // "1080p60", "Audio"
    public var height: Int?
    public var ext: String          // "MP4", "MKV", "M4A"
    public var container: String?   // merge container for yt-dlp
    public var size: Int64?
    public var sizeIsEstimate: Bool = false
    public var format: String       // yt-dlp selector, e.g. "137+140"
    public var audioOnly: Bool
}

public struct SiteFormats: Codable {
    public var title: String
    public var duration: Double?
    public var isLive: Bool
    public var options: [SiteFormatOption]
    /// Whether this list was made with the browser's login cookies; downloads must match it,
    /// because YouTube hands out different formats to signed-in and anonymous players.
    public var useCookies: Bool = false

    var videoHeights: Int { Set(options.compactMap(\.height)).count }
}

enum SiteRules {
    static func isYouTube(_ url: String) -> Bool {
        guard let h = URL(string: url)?.host?.lowercased() else { return false }
        return ["youtube.com", "youtu.be", "youtube-nocookie.com"].contains { h == $0 || h.hasSuffix("." + $0) }
    }

    /// YouTube: anonymous first. With account cookies yt-dlp must use the player clients that
    /// accept them, and YouTube serves those SABR-only streams needing proof-of-origin tokens,
    /// which leaves only the old 360p MP4 (format 18). Other sites: cookies first (Instagram,
    /// Facebook… need the login).
    static func cookieOrder(for url: String, hasCookies: Bool) -> [Bool] {
        guard hasCookies else { return [false] }
        return isYouTube(url) ? [false, true] : [true, false]
    }

    /// Errors that mean "this needs the signed-in session".
    static func needsLogin(_ message: String) -> Bool {
        let l = message.lowercased()
        return ["sign in", "signed in", "login", "log in", "age", "members", "private", "not a bot", "confirm your"].contains { l.contains($0) }
    }
}

/// Site extraction for pages that don't expose plain stream URLs (YouTube's player streams
/// over its own protocol). Uses yt-dlp's extractors behind the scenes; the browser's cookies
/// are passed as a Netscape cookies.txt so logged-in and age-gated videos work.
public final class YTDLPEngine: AsyncEngine {
    let request: DownloadRequest
    let config: EngineConfig
    let outputBase: String
    private let runner = ToolRunner()

    public init(request: DownloadRequest, config: EngineConfig, workDir: URL, outputBase: String) {
        self.request = request
        self.config = config
        self.outputBase = outputBase
        super.init(workDir: workDir)
    }

    public override func stopProcesses() { runner.terminate() }

    static func netscapeCookies(_ cookies: [CookieInfo]) -> String {
        var lines = ["# Netscape HTTP Cookie File", "# Generated by Castnet", ""]
        for c in cookies {
            var domain = c.domain
            let includeSub = !(c.hostOnly ?? !domain.hasPrefix("."))
            if includeSub && !domain.hasPrefix(".") { domain = "." + domain }
            if c.httpOnly == true { domain = "#HttpOnly_" + domain }
            let exp = Int64(c.expirationDate ?? 0)
            let clean = { (s: String) in s.replacingOccurrences(of: "\t", with: " ").replacingOccurrences(of: "\n", with: " ") }
            lines.append([domain, includeSub ? "TRUE" : "FALSE", c.path ?? "/", c.secure == true ? "TRUE" : "FALSE",
                          String(exp), clean(c.name), clean(c.value)].joined(separator: "\t"))
        }
        return lines.joined(separator: "\n") + "\n"
    }

    /// Arguments that make yt-dlp independent of the machine: Castnet's own JavaScript engine,
    /// ffmpeg and cache, no user config files, no self-update prompts.
    static func isolationArgs(config: EngineConfig) -> [String] {
        let cache = Paths.caches.appendingPathComponent("yt-dlp", isDirectory: true)
        var a = ["--ignore-config", "--no-update", "--cache-dir", cache.path]
        if let qjs = Tools.find("qjs") { a += ["--no-js-runtimes", "--js-runtimes", "quickjs:\(qjs.path)"] }
        if let ff = config.ffmpeg { a += ["--ffmpeg-location", ff.deletingLastPathComponent().path] }
        return a
    }

    static func writeCookies(_ cookies: [CookieInfo], in dir: URL) throws -> URL {
        let f = dir.appendingPathComponent("cookies.txt")
        try netscapeCookies(cookies).write(to: f, atomically: true, encoding: .utf8)
        try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: f.path)
        return f
    }

    public override func run() async throws -> [URL] {
        guard let ytdlp = config.ytdlp else { throw CastnetError.toolMissing("yt-dlp") }
        report(0, nil, "Preparing…")
        let hasCookies = !(request.cookies ?? []).isEmpty
        let useCookies = hasCookies && (request.useCookies ?? !SiteRules.isYouTube(request.url))
        var cookies = useCookies
        var format: String? = nil
        let byHeight = request.quality.map { "bv*[height<=\($0)]+ba/b[height<=\($0)]/b" } ?? "bv*+ba/b"
        var attempt = 0
        while true {
            do {
                return try await download(ytdlp: ytdlp, useCookies: cookies, formatOverride: format)
            } catch CastnetError.process(let msg) where !isUserCancelled {
                attempt += 1
                if !cookies && hasCookies && SiteRules.needsLogin(msg) {
                    // The video needs the signed-in session (age-restricted, members-only…).
                    // Format numbers differ between anonymous and signed-in sessions: ask by resolution.
                    report(0, nil, "Signing in…")
                    cookies = true
                    format = byHeight
                    continue
                }
                guard attempt <= 5, Self.isRetryable(msg) else { throw CastnetError.process(msg) }
                // Expired stream links or a dropped connection: extract fresh links and continue
                // the partial file (yt-dlp resumes its .part files).
                if msg.lowercased().contains("format") && msg.lowercased().contains("not available") { format = byHeight }
                report(0, nil, "Link expired, getting a fresh one…")
                await waitUntilOnline()
                try await Task.sleep(nanoseconds: UInt64(min(30, 3 * attempt)) * 1_000_000_000)
            }
        }
    }

    static func isRetryable(_ message: String) -> Bool {
        let l = message.lowercased()
        return ["403", "410", "http error", "expired", "timed out", "timeout", "connection", "reset", "unable to download",
                "giving up", "network", "temporarily", "format is not available", "eof", "incomplete"].contains { l.contains($0) }
    }

    private func download(ytdlp: URL, useCookies: Bool, formatOverride: String? = nil) async throws -> [URL] {
        let cookieFile = workDir.appendingPathComponent("cookies.txt")
        if useCookies { _ = try Self.writeCookies(request.cookies ?? [], in: workDir) }
        defer { try? FileManager.default.removeItem(at: cookieFile) }
        let outDir = workDir.appendingPathComponent("out", isDirectory: true)
        try FileManager.default.createDirectory(at: outDir, withIntermediateDirectories: true)

        var format = formatOverride ?? request.format ?? "bv*+ba/b"
        if formatOverride == nil, request.format == nil, let h = request.quality { format = "bv*[height<=\(h)]+ba/b[height<=\(h)]/bv*+ba/b" }
        let safeBase = outputBase.replacingOccurrences(of: "%", with: "%%")
        var args = [
            request.url,
            "--newline", "--no-playlist", "--no-mtime", "--no-colors", "--no-warnings",
            "-P", "home:\(outDir.path)", "-P", "temp:\(workDir.path)",
            "-o", "\(safeBase).%(ext)s",
            "-f", format,
            "--merge-output-format", request.container ?? "mp4/mkv",
            "--progress", "--progress-template",
            "download:[castnet] %(progress.downloaded_bytes)s|%(progress.total_bytes)s|%(progress.total_bytes_estimate)s|%(info.format_id)s|%(info.vcodec)s",
            "--print", "after_move:[castnet-file] %(filepath)s",
        ]
        args += Self.isolationArgs(config: config)
        if useCookies { args += ["--cookies", cookieFile.path] }
        if let ua = request.userAgent { args += ["--user-agent", ua] }

        var files: [URL] = []
        var lastBytes: Int64 = 0
        var doneBytes: Int64 = 0
        var lastFormat = ""
        let (status, errTail) = try await runner.run(ytdlp, args, cwd: workDir) { line in
            if line.hasPrefix("[castnet-file] ") {
                files.append(URL(fileURLWithPath: String(line.dropFirst(15))))
            } else if line.hasPrefix("[castnet] ") {
                let f = line.dropFirst(10).split(separator: "|", omittingEmptySubsequences: false).map(String.init)
                guard f.count >= 5 else { return }
                let got = Int64(Double(f[0]) ?? 0)
                let total = Int64(Double(f[1]) ?? Double(f[2]) ?? 0)
                if f[3] != lastFormat || got < lastBytes {
                    if !lastFormat.isEmpty { doneBytes += lastBytes }
                    lastFormat = f[3]
                }
                lastBytes = got
                let what = f[4] == "none" ? "Downloading audio" : "Downloading video"
                self.report(doneBytes + got, total > 0 ? doneBytes + total : nil, what)
            } else if line.contains("[Merger]") || line.contains("[VideoRemuxer]") || line.contains("[FixupM3u8]") {
                self.report(doneBytes + lastBytes, nil, "Merging video and audio…")
            }
        }
        if isUserCancelled { throw CancellationError() }
        guard status == 0 else { throw CastnetError.process(Self.friendlyError(errTail, status: status)) }
        if files.isEmpty {
            files = ((try? FileManager.default.contentsOfDirectory(at: outDir, includingPropertiesForKeys: nil)) ?? [])
                .filter { !$0.lastPathComponent.hasPrefix(".") }
        }
        guard !files.isEmpty else { throw CastnetError.process("The site didn't return any video") }
        return files
    }

    static func friendlyError(_ tail: String, status: Int32) -> String {
        let line = tail.split(separator: "\n").last(where: { $0.contains("ERROR") }).map(String.init) ?? tail
        let l = line.lowercased()
        if l.contains("drm") { return "This video is DRM-protected and can't be downloaded." }
        // YouTube's rate limit ("confirm you're not a bot", HTTP 429) is about the network, not the video.
        if l.contains("not a bot") || tail.contains("HTTP Error 429") || l.contains("too many requests") {
            return "The site is limiting downloads from your network right now (too many requests). Wait a while, then try again."
        }
        if l.contains("private video") || l.contains("sign in") || l.contains("login") { return "This video needs you to be signed in, or it's private." }
        if l.contains("unsupported url") { return "No downloadable video was found on this page." }
        if l.contains("unavailable") { return "This video is unavailable." }
        if l.contains("http error 403") { return "The site refused the download (HTTP 403). Reload the page and try again." }
        let msg = line.replacingOccurrences(of: "ERROR: ", with: "")
        return msg.isEmpty ? "Download failed (code \(status))" : String(msg.prefix(200))
    }

    // MARK: - Quality listing

    struct Fmt {
        let id: String, ext: String, vcodec: String, acodec: String
        let height: Int?, fps: Double?, tbr: Double, size: Int64?, exactSize: Bool, direct: Bool, drc: Bool
        var channels: Int? = nil
        var stereo: Int { (channels ?? 2) <= 2 ? 1 : 0 }
        var isVideo: Bool { vcodec != "none" && !vcodec.isEmpty && height != nil }
        var isAudioOnly: Bool { (vcodec == "none") && acodec != "none" && !acodec.isEmpty }
        var hasAudio: Bool { acodec != "none" && !acodec.isEmpty }
        var codecRank: Int {
            let v = vcodec.lowercased()
            if v.hasPrefix("avc") || v.hasPrefix("h264") { return 3 }
            if v.hasPrefix("hvc") || v.hasPrefix("hev") || v.hasPrefix("h265") { return 2 }
            if v.hasPrefix("av01") { return 1 }
            return 0
        }
        var macFriendly: Bool { codecRank > 0 }
    }

    /// Asks yt-dlp for the page's formats and condenses them into one choice per resolution
    /// (best Mac-compatible video + best matching audio), plus an audio-only choice.
    public static func listFormats(request: DownloadRequest, config: EngineConfig) async throws -> SiteFormats {
        let order = SiteRules.cookieOrder(for: request.url, hasCookies: !(request.cookies ?? []).isEmpty)
        let debug = ProcessInfo.processInfo.environment["CASTNET_DEBUG"] != nil
        // Both session types run in parallel (YouTube can take 30 s+ to answer); the first full
        // quality list wins and the other request is stopped. The preferred type gets a head start.
        var finished: [(rank: Int, result: Result<SiteFormats, Error>)] = []
        let winner: SiteFormats? = await withTaskGroup(of: (Int, Result<SiteFormats, Error>).self) { group in
            for (rank, useCookies) in order.enumerated() {
                group.addTask {
                    if rank > 0 { try? await Task.sleep(nanoseconds: 2_000_000_000) }
                    let t0 = Date()
                    do {
                        var f = try await listOnce(request: request, config: config, useCookies: useCookies)
                        f.useCookies = useCookies
                        if debug { FileHandle.standardError.write(Data("attempt cookies=\(useCookies): \(f.videoHeights) heights in \(Int(Date().timeIntervalSince(t0)))s\n".utf8)) }
                        return (rank, .success(f))
                    } catch {
                        if debug { FileHandle.standardError.write(Data("attempt cookies=\(useCookies): \(error) after \(Int(Date().timeIntervalSince(t0)))s\n".utf8)) }
                        return (rank, .failure(error))
                    }
                }
            }
            for await (rank, result) in group {
                finished.append((rank, result))
                if case .success(let f) = result, f.videoHeights >= 2 || (f.videoHeights == 0 && !f.options.isEmpty && order.count == 1) {
                    group.cancelAll()
                    return f
                }
            }
            return nil
        }
        if let winner { return winner }
        // No full list anywhere: take the richest one (preferred session type on ties).
        let ok = finished.compactMap { r -> (Int, SiteFormats)? in if case .success(let f) = r.result { return (r.rank, f) }; return nil }
        if let best = ok.max(by: { ($0.1.videoHeights, -$0.0) < ($1.1.videoHeights, -$1.0) }) { return best.1 }
        let errors = finished.sorted { $0.rank < $1.rank }.compactMap { r -> Error? in if case .failure(let e) = r.result { return e }; return nil }
        throw errors.first ?? CastnetError.process("No video found")
    }

    static func listOnce(request: DownloadRequest, config: EngineConfig, useCookies: Bool) async throws -> SiteFormats {
        guard let ytdlp = config.ytdlp else { throw CastnetError.toolMissing("yt-dlp") }
        let dir = Paths.caches.appendingPathComponent("formats-\(UUID().uuidString)", isDirectory: true)
        try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: dir) }
        var args = [request.url, "-J", "--no-playlist", "--no-warnings", "--no-colors"] + isolationArgs(config: config)
        if useCookies { args += ["--cookies", try writeCookies(request.cookies ?? [], in: dir).path] }
        if let ua = request.userAgent { args += ["--user-agent", ua] }
        if ProcessInfo.processInfo.environment["CASTNET_DEBUG"] != nil {
            FileHandle.standardError.write(Data("tools: \(ytdlp.path) \(args.filter { $0.hasPrefix("quickjs:") || $0.hasPrefix("/") && $0.contains("Helpers") }.joined(separator: " "))\n".utf8))
        }
        let (status, out, err) = try await runCapture(ytdlp, args, timeout: 85)
        guard status == 0, var info = try? JSONSerialization.jsonObject(with: out) as? [String: Any] else {
            throw CastnetError.process(friendlyError(err, status: status))
        }
        if let entries = info["entries"] as? [[String: Any]], let first = entries.first { info = first }
        return condense(info)
    }

    static func condense(_ info: [String: Any]) -> SiteFormats {
        func num(_ v: Any?) -> Double? { (v as? NSNumber)?.doubleValue }
        let raw = (info["formats"] as? [[String: Any]]) ?? [info]
        let fmts: [Fmt] = raw.compactMap { f in
            guard let id = f["format_id"] as? String ?? (info["format_id"] as? String) else { return nil }
            if (f["has_drm"] as? Bool) == true { return nil }
            let proto = (f["protocol"] as? String) ?? ""
            let ext = (f["ext"] as? String) ?? "mp4"
            if proto == "mhtml" || ext == "mhtml" { return nil }
            let tbr = num(f["tbr"]) ?? 0
            let exact = num(f["filesize"])
            // Unknown size (HLS-delivered formats): estimate from bitrate × duration.
            let est = num(f["filesize_approx"]) ?? (tbr > 0 ? num(info["duration"]).map { tbr * 1000 / 8 * $0 } : nil)
            let note = ((f["format_note"] as? String) ?? "").lowercased()
            return Fmt(id: id, ext: ext, vcodec: (f["vcodec"] as? String) ?? (num(f["height"]) != nil ? "unknown" : "none"),
                       acodec: (f["acodec"] as? String) ?? "unknown",
                       height: num(f["height"]).map { Int($0) }, fps: num(f["fps"]), tbr: tbr,
                       size: (exact ?? est).map { Int64($0) }, exactSize: exact != nil,
                       direct: proto.hasPrefix("http") && !proto.contains("m3u8"),
                       drc: id.contains("drc") || note.contains("drc"),
                       channels: num(f["audio_channels"]).map { Int($0) })
        }
        let allAudio = fmts.filter(\.isAudioOnly)
        let audios = allAudio.contains { !$0.drc } ? allAudio.filter { !$0.drc } : allAudio  // skip volume-compressed variants
        // Normal stereo first (plays everywhere, sensible size), then bitrate.
        let bestM4A = audios.filter { $0.ext == "m4a" || $0.ext == "mp4" }.max { ($0.stereo, $0.tbr) < ($1.stereo, $1.tbr) }
        let bestAny = audios.max { ($0.stereo, $0.tbr) < ($1.stereo, $1.tbr) }

        var options: [SiteFormatOption] = []
        let heights = Set(fmts.filter(\.isVideo).compactMap(\.height)).sorted(by: >)
        for h in heights.prefix(8) {
            let cands = fmts.filter { $0.isVideo && $0.height == h }
            // Mac-friendly codec, frame rate, separate video stream (paired with the best audio), direct HTTP, bitrate.
            func rank(_ f: Fmt) -> (Int, Double, Int, Int, Double) { (f.codecRank, f.fps ?? 0, f.hasAudio ? 0 : 1, f.direct ? 1 : 0, f.tbr) }
            guard let v = cands.max(by: { rank($0) < rank($1) }) else { continue }
            var format = v.id
            var size = v.size
            var estimate = !v.exactSize
            var container = v.ext == "webm" ? "webm" : "mp4"
            if !v.hasAudio, let a = (v.macFriendly ? (bestM4A ?? bestAny) : (bestAny ?? bestM4A)) {
                format = "\(v.id)+\(a.id)"
                if let s = a.size { size = (size ?? 0) + s }
                if !a.exactSize { estimate = true }
                let aMac = a.ext == "m4a" || a.ext == "mp4"
                container = v.macFriendly && aMac ? "mp4" : (v.ext == "webm" && a.ext == "webm" ? "webm" : "mkv")
            }
            let fps = (v.fps ?? 0) > 31 ? "\(Int((v.fps ?? 0).rounded()))" : ""
            options.append(SiteFormatOption(id: "v\(h)", label: "\(h)p\(fps)", height: h, ext: container.uppercased(),
                                            container: container, size: size, sizeIsEstimate: estimate, format: format, audioOnly: false))
        }
        if options.isEmpty, let v = fmts.first(where: { !$0.isAudioOnly }) {
            options.append(SiteFormatOption(id: "best", label: "Best quality", height: nil, ext: v.ext.uppercased(),
                                            container: nil, size: v.size, sizeIsEstimate: !v.exactSize, format: "bv*+ba/b", audioOnly: false))
        }
        if let a = bestM4A ?? bestAny {
            options.append(SiteFormatOption(id: "audio", label: "Audio", height: nil, ext: a.ext == "webm" ? "OPUS" : a.ext.uppercased(),
                                            container: nil, size: a.size, sizeIsEstimate: !a.exactSize, format: a.id, audioOnly: true))
        }
        return SiteFormats(title: (info["title"] as? String) ?? "video", duration: num(info["duration"]),
                           isLive: (info["is_live"] as? Bool) ?? false, options: options)
    }

    /// Runs a tool and returns (status, stdout, stderr), killing it after `timeout` seconds.
    static func runCapture(_ exe: URL, _ args: [String], timeout: TimeInterval) async throws -> (Int32, Data, String) {
        let p = Process()
        p.executableURL = exe
        p.arguments = args
        var env = ProcessInfo.processInfo.environment
        env["PATH"] = (Tools.searchDirs + [env["PATH"] ?? ""]).joined(separator: ":")
        p.environment = env
        let out = Pipe(), err = Pipe()
        p.standardOutput = out
        p.standardError = err
        p.standardInput = FileHandle.nullDevice
        let buf = DataBox(), ebuf = DataBox()
        out.fileHandleForReading.readabilityHandler = { h in let d = h.availableData; if d.isEmpty { h.readabilityHandler = nil } else { buf.append(d) } }
        err.fileHandleForReading.readabilityHandler = { h in let d = h.availableData; if d.isEmpty { h.readabilityHandler = nil } else { ebuf.append(d) } }
        return try await withTaskCancellationHandler {
          try await withCheckedThrowingContinuation { cont in
            p.terminationHandler = { proc in
                out.fileHandleForReading.readabilityHandler = nil
                err.fileHandleForReading.readabilityHandler = nil
                if let rest = try? out.fileHandleForReading.readToEnd() { buf.append(rest) }
                if let rest = try? err.fileHandleForReading.readToEnd() { ebuf.append(rest) }
                cont.resume(returning: (proc.terminationStatus, buf.data, String(decoding: ebuf.data, as: UTF8.self)))
            }
            do { try p.run() } catch { cont.resume(throwing: error); return }
            DispatchQueue.global().asyncAfter(deadline: .now() + timeout) { if p.isRunning { p.terminate() } }
          }
        } onCancel: {
            if p.isRunning { p.terminate() }
        }
    }
}

final class DataBox {
    private var d = Data()
    private let lock = NSLock()
    func append(_ x: Data) { lock.lock(); d.append(x); lock.unlock() }
    var data: Data { lock.lock(); defer { lock.unlock() }; return d }
}
